def ask(prompt: str, *, non_interactive: bool = False, value: str | None = None) -> str:
    if value is not None:
        return value
    if non_interactive:
        raise ValueError("non-interactive mode requires a value for: " + prompt.rstrip(": "))
    return input(prompt).strip()


def backup_path(path: Path) -> Path:
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    candidate = path.with_name(path.name + "." + stamp + ".bak")
    counter = 1
    while candidate.exists() or candidate.is_symlink():
        candidate = path.with_name(path.name + "." + stamp + "." + str(counter) + ".bak")
        counter += 1
    if path.is_symlink():
        # Preserve the link itself, including its target, without dereferencing it.
        os.symlink(os.readlink(path), candidate)
    elif path.is_dir():
        shutil.copytree(path, candidate, symlinks=True)
    else:
        with path.open("rb") as source, candidate.open("xb") as destination:
            shutil.copyfileobj(source, destination)
        shutil.copystat(path, candidate, follow_symlinks=False)
    return candidate


def move_to_backup(path: Path) -> Path:
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    candidate = path.with_name(path.name + "." + stamp + ".bak")
    counter = 1
    while candidate.exists() or candidate.is_symlink():
        candidate = path.with_name(path.name + "." + stamp + "." + str(counter) + ".bak")
        counter += 1
    os.rename(path, candidate)
    return candidate


def rewrite_preserving(path: Path, content: str) -> bool:
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    if old == content:
        return False
    if path.exists():
        saved = backup_path(path)
        print("Backup: " + str(saved))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def query_print_state(url: str, timeout: float = 3.0) -> str:
    parsed = urllib.parse.urlsplit(url)
    if (parsed.scheme not in ("http", "https") or not parsed.hostname or parsed.username or
            parsed.password or parsed.query or parsed.fragment):
        raise ValueError("Moonraker URL must be an HTTP(S) base URL without credentials or query data")
    base = url.rstrip("/")
    endpoint = base + "/printer/objects/query?print_stats"
    request = urllib.request.Request(endpoint, headers={"Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        data = json.loads(response.read().decode("utf-8"))
    state = data.get("result", {}).get("status", {}).get("print_stats", {}).get("state")
    return state.lower() if isinstance(state, str) else "unknown"


def require_idle(url: str, force: bool = False) -> str:
    try:
        state = query_print_state(url)
    except (OSError, ValueError, urllib.error.URLError, json.JSONDecodeError):
        state = "unknown"
    if state in ("printing", "paused"):
        raise ValueError("Moonraker reports %s; refusing to proceed" % state)
    if state == "unknown" and not force:
        raise ValueError("Moonraker print state is unknown; use --force only if independently verified idle")
    return state


def section_names(path: Path) -> list[str]:
    return [m.group(1).strip() for m in re.finditer(r"(?m)^\s*\[([^]\n]+)\]\s*(?:#.*)?$", path.read_text(encoding="utf-8"))]


def included_files(printer_cfg: Path) -> list[Path]:
    root = printer_cfg.parent
    pending = [printer_cfg.resolve()]
    visited: set[Path] = set()
    result: list[Path] = []
    include_re = re.compile(r"(?im)^\s*\[include\s+([^]\n]+)\]\s*(?:#.*)?$")
    while pending:
        current = pending.pop()
        if current in visited or not current.is_file():
            continue
        visited.add(current)
        result.append(current)
        text = current.read_text(encoding="utf-8")
        for match in include_re.finditer(text):
            expression = match.group(1).strip()
            pattern = Path(expression)
            if not pattern.is_absolute():
                pattern = root / pattern
            for item in glob.glob(str(pattern), recursive=True):
                target = Path(item).resolve()
                if target.is_file() and target not in visited:
                    pending.append(target)
    return result


def detect_config(printer_cfg: Path) -> tuple[list[str], list[str]]:
    names: list[str] = []
    sensors: list[str] = []
    for file in included_files(printer_cfg):
        for section in section_names(file):
            if section.lower() == "extruder":
                names.append(section)
            match = re.fullmatch(r"filament_switch_sensor\s+(.+)", section, re.I)
            if match:
                sensors.append(match.group(1).strip())
    return names, sorted(set(sensors), key=str.lower)


def normalize_include(text: str) -> str:
    return "\n".join(line for line in text.splitlines()
                     if line.strip().lower() != INCLUDE_LINE.lower())


def canvas_settings(printer_cfg: Path) -> dict[str, dict[str, str]]:
    settings: dict[str, dict[str, str]] = {}
    current = None
    seen_sections: set[str] = set()
    duplicate_sections = False
    for path in included_files(printer_cfg):
        for line in path.read_text(encoding="utf-8").splitlines():
            header = re.fullmatch(r"\s*\[([^]\n]+)\]\s*(?:#.*)?", line)
            if header:
                current = header.group(1).strip().casefold()
                if current in seen_sections:
                    duplicate_sections = True
                seen_sections.add(current)
                settings.setdefault(current, {})
                continue
            if current is None or not line.strip() or line.lstrip().startswith("#"):
                continue
            option = re.match(r"\s*([A-Za-z0-9_.-]+)\s*[:=]\s*(.*?)\s*(?:#.*)?$", line)
            if option:
                settings[current][option.group(1).casefold()] = option.group(2).strip()
    if duplicate_sections:
        settings["__duplicate_sections__"] = {}
    return settings


def canvas_config_complete(printer_cfg: Path) -> bool:
    settings = canvas_settings(printer_cfg)
    if "__duplicate_sections__" in settings:
        return False
    canvas = settings.get("canvas", {})
    serial = settings.get("mcu canvas", {}).get("serial", "")
    sensor = canvas.get("toolhead_sensor", "")
    if not serial or not sensor or "TO_BE_MEASURED" in serial.upper():
        return False
    sensor_pin = settings.get(("filament_switch_sensor " + sensor).casefold(), {}).get("switch_pin", "")
    if not sensor_pin or "TO_BE_MEASURED" in sensor_pin.upper():
        return False
    for lane in range(4):
        key = "lane_t%d_" % lane
        motor = canvas.get(key + "motor", "")
        lane_values = (motor, canvas.get(key + "present_pin", ""), canvas.get(key + "prep_pin", ""))
        if any(not value or "TO_BE_MEASURED" in value.upper() for value in lane_values):
            return False
        driver = settings.get(("drv8833 " + motor).casefold(), {})
        if any(not driver.get(option) or "TO_BE_MEASURED" in driver.get(option, "").upper()
               for option in ("motor_fwd", "motor_rwd", "motor_hall", "motor_hall_resolution")):
            return False
    return True


def update_option(text: str, section: str, key: str, value: str) -> str:
    header = re.compile(r"(?m)^\s*\[" + re.escape(section) + r"\]\s*(?:#.*)?$")
    match = header.search(text)
    if not match:
        raise ValueError("generated Canvas config is missing [%s]" % section)
    next_header = re.compile(r"(?m)^\s*\[[^]\n]+\]")
    following = next_header.search(text, match.end())
    end = following.start() if following else len(text)
    block = text[match.start():end]
    option = re.compile(r"(?m)^(\s*" + re.escape(key) + r"\s*[:=]\s*).*$", re.I)
    if option.search(block):
        block = option.sub(lambda m: m.group(1) + value, block, count=1)
    else:
        position = block.find("\n") + 1
        block = block[:position] + key + ": " + value + "\n" + block[position:]
    return text[:match.start()] + block + text[end:]


def make_canvas_config(sensor: str, method: str, serial: str, add_sensor_pin: str | None) -> str:
    template = (ROOT / "config/canvas.cfg").read_text(encoding="utf-8")
    template = re.sub(r"(?ms)^\[filament_switch_sensor\s+[^]\n]+\]\n.*?(?=^\[|\Z)", "", template)
    template = re.sub(r"(?im)^\s*\[include\s+canvas_macros\.cfg\]\s*\n", "", template)
    template = re.sub(r"(?m)^toolhead_sensor\s*:\s*.*$", "toolhead_sensor: " + sensor, template)
    template = re.sub(r"(?m)^separation_method\s*:\s*.*$", "separation_method: " + method, template)
    mcu = "[mcu canvas]\nserial: " + serial + "\n\n"
    if add_sensor_pin:
        mcu += "[filament_switch_sensor %s]\nswitch_pin: %s\npause_on_runout: False\n\n" % (sensor, add_sensor_pin)
    return MANAGED_HEADER + "\n" + mcu + template.lstrip()


def copy_templates(config_dir: Path, sensor: str, method: str, serial: str,
                   new_sensor_pin: str | None) -> bool:
    canvas_dir = config_dir / "canvas"
    canvas_dir.mkdir(parents=True, exist_ok=True)
    generated = {
        "canvas.cfg": make_canvas_config(sensor, method, serial, new_sensor_pin),
        "canvas_macros.cfg": (ROOT / "config/canvas_macros.cfg").read_text(encoding="utf-8"),
        "slicer-snippets.cfg.example": (ROOT / "config/slicer-snippets.cfg").read_text(encoding="utf-8"),
    }
    changed = False
    for name, content in generated.items():
        path = canvas_dir / name
        if path.exists():
            if not path.is_file():
                raise ValueError("Refusing to replace non-file user path: " + str(path))
            if name != "canvas.cfg":
                continue  # These copied templates may now contain user edits; never overwrite them.
            current = path.read_text(encoding="utf-8")
            if not current.startswith(MANAGED_HEADER):
                raise ValueError("Refusing to overwrite unmarked user file: " + str(path))
            content = current
            for section, key, value in (("mcu canvas", "serial", serial),
                                        ("canvas", "toolhead_sensor", sensor),
                                        ("canvas", "separation_method", method)):
                content = update_option(content, section, key, value)
            changed |= rewrite_preserving(path, content)
        else:
            with path.open("x", encoding="utf-8") as destination:
                destination.write(content)
            changed = True
    return changed


def config_digest(config_dir: Path, printer_cfg: Path, moonraker_cfg: Path) -> str:
    digest = hashlib.sha256()
    paths = [printer_cfg, moonraker_cfg, *sorted((config_dir / "canvas").glob("*.cfg"))]
    for path in paths:
        digest.update(str(path.name).encode("utf-8") + b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


