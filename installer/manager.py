def load_flasher():
    loader = importlib.machinery.SourceFileLoader("canvas_flash", str(FLASH_SCRIPT))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


flash_tool = load_flasher()
